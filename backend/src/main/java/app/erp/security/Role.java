package app.erp.security;

import static app.erp.security.Perm.*;

import java.util.EnumSet;
import java.util.Set;

/** Tenant roles from the PRD. Platform operator is a user flag, not a tenant role. */
public enum Role {
    OWNER(EnumSet.complementOf(EnumSet.of(SELF_SERVICE, CLIENT_PORTAL, ATTENDANCE_SELF, LEAVE_SELF))),
    HR(EnumSet.of(MASTER_READ, HR_READ, HR_WRITE, HR_VERIFY, CLIENT_READ, PAYRATE_READ, ROSTER_READ,
            ATTENDANCE_READ, LEAVE_APPROVE, PAYROLL_READ, REPORT_READ, USER_MANAGE)),
    OPERATIONS(EnumSet.of(MASTER_READ, MASTER_WRITE, HR_READ, CLIENT_READ, CLIENT_WRITE, CONTRACT_READ, ROSTER_READ, ROSTER_WRITE,
            ATTENDANCE_READ, ATTENDANCE_MARK, ATTENDANCE_ADJUST, ATTENDANCE_APPROVE, LEAVE_APPROVE,
            INCIDENT_REPORT, INCIDENT_READ, INCIDENT_MANAGE, REPORT_READ)),
    SUPERVISOR(EnumSet.of(MASTER_READ, HR_READ, CLIENT_READ, ROSTER_READ, ROSTER_WRITE, ATTENDANCE_READ, ATTENDANCE_MARK,
            ATTENDANCE_ADJUST, ATTENDANCE_SELF, INCIDENT_REPORT, INCIDENT_READ, INCIDENT_MANAGE, LEAVE_SELF, SELF_SERVICE)),
    FINANCE(EnumSet.of(MASTER_READ, HR_READ, CLIENT_READ, CONTRACT_READ, CONTRACT_WRITE, PAYRATE_READ, PAYRATE_WRITE,
            ROSTER_READ, ATTENDANCE_READ, PAYROLL_READ, PAYROLL_RUN, PAYROLL_APPROVE,
            BILLING_READ, BILLING_WRITE, BILLING_APPROVE, RECEIPT_WRITE, REPORT_READ)),
    CLIENT_ADMIN(EnumSet.of(CLIENT_PORTAL, INCIDENT_REPORT, INCIDENT_READ)),
    CLIENT_VIEWER(EnumSet.of(CLIENT_PORTAL, INCIDENT_READ)),
    GUARD(EnumSet.of(SELF_SERVICE, ATTENDANCE_SELF, LEAVE_SELF, INCIDENT_REPORT)),
    AUDITOR(EnumSet.of(MASTER_READ, HR_READ, CLIENT_READ, CONTRACT_READ, PAYRATE_READ, ROSTER_READ, ATTENDANCE_READ,
            PAYROLL_READ, BILLING_READ, INCIDENT_READ, REPORT_READ, AUDIT_READ));

    private final Set<Perm> perms;

    Role(Set<Perm> perms) { this.perms = perms; }

    public Set<Perm> perms() { return perms; }
}
